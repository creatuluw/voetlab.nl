def _esc(s: str) -> str:
    return (s or "").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def write_html(rows) -> Path:
    by_folder = {}
    for r in rows:
        by_folder.setdefault(r["folder"], []).append(r)
    nav = "\n".join(
        '<details class="nav-group" open><summary>' + f + "</summary>" +
        "".join(f'<a href="#{f}-{r["file"]}">{r["file"]}</a>' for r in items) +
        "</details>"
        for f, items in by_folder.items()
    )
    cards = "\n".join(
        f'<section class="card" id="{r["folder"]}-{r["file"]}"><h2>{r["folder"]}/<span>{r["file"]}</span></h2>'
        f'<p class="summary">{_esc(r["summary"])}</p>'
        f'<details><summary>Quality &amp; when to use</summary><pre>{_esc(r["quality"]) or "(see source)"}</pre></details>'
        f'</section>'
        for r in rows
    )
    html = _HTML_TEMPLATE.replace("__NAV__", nav).replace("__CARDS__", cards).replace("__N__", str(len(rows)))
    out_dir = PROJECT / "docs" / "site"
    out_dir.mkdir(parents=True, exist_ok=True)
    out = out_dir / "index.html"
    out.write_text(html, encoding="utf-8")
    return out


def main():
    rows = collect()
    md = write_markdown(rows)
    html = write_html(rows)
    print(f"wrote {md} ({len(rows)} features)")
    print(f"wrote {html}")


if __name__ == "__main__":
    main()
