"""F6 — generate pitchkit docs (markdown manifest + self-contained HTML site) from source.

Scans every feature .py under pitchkit/pitchkit, extracts the module-docstring summary and
the `# === Quality & when to use ===` block, and emits:
  - FEATURES.md          (a manifest table — one row per feature file)
  - docs/site/index.html (self-contained: sidebar nav, collapsible cards, search, dark mode)

Run:  python -m pitchkit.docs.build_docs
Stays in sync with the code — re-run after adding a feature.
"""
from __future__ import annotations

import ast
from pathlib import Path

PKG = Path(__file__).resolve().parents[1]  # .../pitchkit/pitchkit
PROJECT = PKG.parent                        # .../pitchkit
FEATURE_FOLDERS = ["core", "detection", "tracking", "calibration", "events", "stats",
                   "tactics", "reliability", "viz", "pipeline"]


def _summary(text: str) -> str:
    m = ast.get_docstring(ast.parse(text))
    return (m or "").strip().splitlines()[0] if (m or "").strip() else "(no docstring)"


def _quality_block(text: str) -> str:
    out, capturing = [], False
    for ln in text.splitlines():
        if "# === Quality & when to use" in ln:
            capturing = True
            continue
        if capturing:
            s = ln.lstrip()
            if s.startswith("#"):
                out.append(s[2:] if s.startswith("# ") else s[1:])
            else:
                break
    return "\n".join(out).strip()


def collect():
    rows = []
    for folder in FEATURE_FOLDERS:
        d = PKG / folder
        if not d.is_dir():
            continue
        for py in sorted(d.glob("*.py")):
            if py.name == "__init__.py":
                continue
            text = py.read_text(encoding="utf-8")
            rows.append({"folder": folder, "file": py.name, "path": f"{folder}/{py.name}",
                         "summary": _summary(text), "quality": _quality_block(text)})
    return rows


def write_markdown(rows) -> Path:
    out = PROJECT / "FEATURES.md"
    lines = ["# pitchkit — feature manifest", "",
             "Auto-generated by `pitchkit/docs/build_docs.py`. One row per feature file.", "",
             "| Folder | File | Summary |", "|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['folder']} | `{r['file']}` | {r['summary']} |")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


